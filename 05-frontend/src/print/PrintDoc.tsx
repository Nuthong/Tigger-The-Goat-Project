import type { ReactNode } from "react";
import { useNavigate } from "react-router-dom";
import { HOTEL } from "../lib/hotel";

/**
 * The hotel crest for paper. `/logo.png` is a white crest with a glow, made for
 * dark surfaces; `/logo-ink.png` is the same artwork (taken from its alpha
 * channel) in dark ink on a transparent ground, so it prints crisp on white.
 */
const CREST_INK = "/logo-ink.png";

/** Letterhead details, derived from the shared hotel identity (`lib/hotel`). */
const LETTERHEAD = {
  name: HOTEL.name,
  sub: HOTEL.city.toUpperCase(),
  taxId: HOTEL.taxId,
  lines: [...HOTEL.addressLines, `${HOTEL.phone} · ${HOTEL.email}`],
};

export interface MetaItem {
  label: string;
  value: string;
}

/**
 * The shared shell for a printable document (tax invoice, guest folio): house
 * letterhead, a title, a two-column meta block and a thank-you footer. The
 * action bar carries a Back link and Print button and is hidden when printing.
 */
export function PrintDoc({
  docTitle,
  meta,
  backTo,
  children,
  watermark = false,
}: {
  docTitle: string;
  meta: MetaItem[];
  backTo: string;
  children: ReactNode;
  /** Faint hotel-crest watermark behind the document body - used for the tax invoice. */
  watermark?: boolean;
}) {
  const nav = useNavigate();
  return (
    <div className="printpage">
      <div className="printbar no-print">
        <button className="btn btn--sm btn--quiet" onClick={() => nav(backTo)}>
          Back
        </button>
        <button className="btn btn--sm btn--gold" onClick={() => window.print()}>
          Print / Save PDF
        </button>
      </div>

      <div className="printdoc">
        {watermark && (
          <div className="printdoc__watermark" aria-hidden>
            <img src="/logo.png" alt="" />
          </div>
        )}
        <div className="printdoc__head">
          <div className="printdoc__ident">
            <img className="printdoc__crest" src={CREST_INK} alt={LETTERHEAD.name} />
            <small className="printdoc__brand">
              {LETTERHEAD.sub} · {LETTERHEAD.taxId}
            </small>
          </div>
          <div className="printdoc__meta">
            {LETTERHEAD.lines.map((l) => (
              <div key={l}>{l}</div>
            ))}
          </div>
        </div>

        <h1 className="printdoc__title">{docTitle}</h1>

        <div className="printdoc__cols">
          {meta.map((m) => (
            <div key={m.label}>
              <h4>{m.label}</h4>
              <div>{m.value}</div>
            </div>
          ))}
        </div>

        {children}

        <div className="printdoc__foot">
          Thank you for staying with us. · Generated by the Tigger Oriental front office system.
        </div>
      </div>
    </div>
  );
}
