const DICTS: Record<Lang, Record<MsgKey, string>> = { en: EN, th: TH };

/**
 * Look up a message. Falls back to English, then to the key itself, so a missing
 * translation degrades visibly-but-safely rather than throwing. `vars` fills
 * `{name}` placeholders.
 */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang] ?? EN;
  let out: string = (dict as Record<string, string>)[key] ?? EN[key as MsgKey] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}

/** The language to start in: a saved choice, else the browser's, else English. */
export function pickInitialLang(
  stored: string | null,
  navLang: string | undefined = undefined,
): Lang {
  if (stored === "en" || stored === "th") return stored;
  return navLang?.toLowerCase().startsWith("th") ? "th" : "en";
}
