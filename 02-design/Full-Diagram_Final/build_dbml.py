#!/usr/bin/env python3
"""Generate FULL-ERD-Diagram.dbml (dbdiagram.io / dbdocs source) from schema.sql.

The PNG / SVG / PDF next to it are exports of the dbdiagram.io diagram
"MiniProject-Database", which keeps the hand-arranged layout. This file is the reference
for that diagram's refs: when schema.sql changes, regenerate it and carry the ref / unique
changes over to dbdiagram.io by hand (do not paste it whole - that resets the layout).
Cardinality comes from the DDL, so the refs cannot drift from the database:
  - FK column declared UNIQUE          -> one-to-one ref  (-)   e.g. review.booking_id
  - UNIQUE only among some rows (WHERE) -> one-to-many ref (<)  + a note ("one live")
  - anything else                       -> one-to-many ref (<)

run: python 02-design/Full-Diagram_Final/build_dbml.py
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "Draft"))

from build_erd import SCHEMA, parse_schema, relationships  # noqa: E402

_TYPES = {"int": "int", "bigint": "bigint", "varchar": "varchar", "numeric": "decimal",
          "boolean": "boolean", "date": "date", "timestamptz": "timestamptz",
          "inet": "inet", "jsonb": "jsonb", "text": "text", "char": "char"}


def main() -> None:
    tables = parse_schema(SCHEMA.read_text(encoding="utf-8"))
    rels = relationships(tables)
    out = ["// generated by build_dbml.py from 03-database/schema.sql - do not edit by hand", ""]
    for t in tables:
        out.append(f"Table {t.name} {{")
        for c in t.columns:
            settings = []
            if c.pk:
                settings.append("pk")
            if c.unique and not c.pk:
                settings.append("unique")
            if c.not_null and not c.pk:
                settings.append("not null")
            if c.name in t.partial_unique:
                settings.append("note: 'unique among non-void rows'")
            tail = f" [{', '.join(settings)}]" if settings else ""
            out.append(f"  {c.name} {_TYPES.get(c.type, c.type)}{tail}")
        out.append("}")
        out.append("")
    for r in rels:
        kind = "-" if r.one_to_one else "<"
        out.append(f"Ref: {r.parent}.{_pk(tables, r.parent)} {kind} {r.child}.{r.fk_column}")
    (HERE / "FULL-ERD-Diagram.dbml").write_text("\n".join(out) + "\n", encoding="utf-8")
    one = sum(r.one_to_one for r in rels)
    print(f"wrote FULL-ERD-Diagram.dbml: {len(tables)} tables, {len(rels)} refs ({one} one-to-one)")


def _pk(tables: list, name: str) -> str:
    t = next(t for t in tables if t.name == name)
    return next(c.name for c in t.columns if c.pk)


if __name__ == "__main__":
    main()
